// Fonction pour récupérer 16 histoires mélangées ou paginées pour un sujet donné
export function get16StoriesForTopic(topicId: string, shuffleSeed: number = 0): AffiliationPerson[] {
  const topic = EXPLORER_TOPICS_DATA.find(t => t.id === topicId);
  if (!topic || !topic.storiesPool || topic.storiesPool.length === 0) {
    return [];
  }

  const pool = [...topic.storiesPool];
  if (shuffleSeed > 0) {
    // Rotation ou permutation déterministe
    const offset = (shuffleSeed * 5) % pool.length;
    const rotated = [...pool.slice(offset), ...pool.slice(0, offset)];
    return rotated.slice(0, 16);
  }

  return pool.slice(0, 16);
}
